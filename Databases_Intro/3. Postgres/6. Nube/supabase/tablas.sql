-- ------------------------------------------------------------------------------
-- 1. LIMPIEZA PREVIA (Opcional, por si ya existían de pruebas anteriores)
-- ------------------------------------------------------------------------------
DROP TABLE IF EXISTS libros CASCADE;
DROP TABLE IF EXISTS autores CASCADE;

-- ------------------------------------------------------------------------------
-- 2. CREACIÓN DE LA TABLA 'autores' (Tabla Padre)
-- ------------------------------------------------------------------------------
-- ¿Qué es una clave primaria (PRIMARY KEY)?
-- Es el identificador único irrepetible de cada fila. Usamos 'BIGINT GENERATED BY DEFAULT AS IDENTITY'
-- o 'SERIAL', que es el estándar moderno en PostgreSQL para autoincrementar (1, 2, 3...).
CREATE TABLE autores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    pais VARCHAR(50) NOT NULL,
    activo BOOLEAN DEFAULT true,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 3. CREACIÓN DE LA TABLA 'libros' (Tabla Hija con Clave Foránea)
-- ------------------------------------------------------------------------------
-- ¿Qué es una clave foránea (FOREIGN KEY)?
-- Conecta un libro con su autor mediante 'REFERENCES autores(id)'.
-- 'ON DELETE CASCADE' significa que si se elimina un autor, sus libros se borran automáticamente.
CREATE TABLE libros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id BIGINT REFERENCES autores(id) ON DELETE CASCADE,
    titulo VARCHAR(150) NOT NULL,
    genero VARCHAR(50) NOT NULL,
    precio NUMERIC(6, 2) NOT NULL,
    paginas INT,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

