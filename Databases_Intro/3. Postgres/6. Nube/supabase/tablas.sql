-- ------------------------------------------------------------------------------
-- 5. CONSULTA DE COMPROBACIÓN CON UNIÓN (JOIN)
-- ------------------------------------------------------------------------------
-- Verifica que todo se ha creado correctamente mostrando el libro con el nombre de su autor:
SELECT 
    libros.id AS libro_id,
    libros.titulo,
    libros.genero,
    libros.precio,
    autores.nombre AS autor,
    autores.pais
FROM libros
JOIN autores ON libros.autor_id = autores.id
ORDER BY libros.id ASC;
