    neighborhood_id INT PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    avg_income_eur NUMERIC(10,2) NOT NULL,
    safety_score NUMERIC(3,1) NOT NULL,
    distance_center_km NUMERIC(4,2) NOT NULL,
    schools_count INT NOT NULL
